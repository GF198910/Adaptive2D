# Figure 5: 汇总柱状图 — 从 CSV 原始数据绘制
# ================================================================
def make_fig5():
    df = pd.read_csv(os.path.join(BASE, "extended_benchmark_results.csv"))
    # 筛选 rel_tol=0.001
    df = df[df["rel_tol"] == 0.001].copy()
    
    datasets = df["dataset"].unique()
    n = len(datasets)
    x = np.arange(n)
    width = 0.35
    
    fig, axes = plt.subplots(2, 2, figsize=(13, 7))
    
    # (a) Overall MSE
    ax = axes[0, 0]
    dp = df[df["codec"] == "daspack"].set_index("dataset").loc[datasets]
    ad = df[df["codec"] == "adaptive_2d"].set_index("dataset").loc[datasets]
    ax.bar(x - width/2, dp["mse"], width, color=C_DP, label="DASPack", edgecolor="white", linewidth=0.5)
    ax.bar(x + width/2, ad["mse"], width, color=C_AD, label="Adaptive2D", edgecolor="white", linewidth=0.5)
