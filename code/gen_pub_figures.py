# Figure 1: 率失真曲线 (Alboran + Castor)
# ================================================================
def make_fig1():
    df = pd.read_csv(os.path.join(BASE, "rate_distortion_results.csv"))
    
    fig, axes = plt.subplots(2, 3, figsize=(13, 6.5))
    
    datasets = [("alboran", "Alboran"), ("castor", "Castor")]
    metrics = [
        ("mse", "Overall MSE", "MSE"),
        ("mse_high", "High-energy MSE", "MSE$_\\mathrm{high}$"),
        ("mse_low", "Low-energy MSE", "MSE$_\\mathrm{low}$"),
    ]
    
    for row, (ds_key, ds_name) in enumerate(datasets):
        sub = df[df["dataset"] == ds_key].sort_values("epsilon")
        dp = sub[sub["codec"] == "daspack"]
        ad = sub[sub["codec"] == "adaptive_2d"]
        
        for col, (metric, title, ylabel) in enumerate(metrics):
            ax = axes[row, col]
            
            ax.plot(dp["cr"], dp[metric], "o-", color=C_DP, label="DASPack",
                    markersize=5, markeredgecolor="white", markeredgewidth=0.5)
            ax.plot(ad["cr"], ad[metric], "s-", color=C_AD, label="Adaptive2D",
                    markersize=5, markeredgecolor="white", markeredgewidth=0.5)
            
            ax.set_xlabel("Compression Ratio")
            ax.set_ylabel(ylabel)
            if row == 0:
                ax.set_title(title, fontweight="bold")
            if col == 0:
                ax.annotate(ds_name, xy=(0.02, 0.95), xycoords="axes fraction",
                           va="top", fontsize=11, fontweight="bold",
                           bbox=dict(boxstyle="round,pad=0.3", facecolor="white",
                                     edgecolor=C_GREY, alpha=0.9))
            ax.set_yscale("log")
            ax.legend(loc="lower left", framealpha=0.9)
    
    plt.tight_layout(pad=0.5, h_pad=0.8, w_pad=0.8)
    fig.savefig(os.path.join(OUT, "fig1_rate_distortion.png"), bbox_inches="tight",
                facecolor="white", edgecolor="none")
    plt.close()
    print("Figure 1 done (rate-distortion)")

