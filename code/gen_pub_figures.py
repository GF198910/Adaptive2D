# Figure 4: 参数敏感性 (Block size + Fraction) — 从 CSV 原始数据绘制
# ================================================================
def make_fig4():
    # --- Block size sweep ---
    df_blk = pd.read_csv(os.path.join(BASE, "param_sensitivity_plots/sweep_block_size.csv"))
    # --- Fraction sweep ---
    df_frac = pd.read_csv(os.path.join(BASE, "param_sensitivity_plots/sweep_fraction.csv"))
    
    # 只选 3 个代表性数据集
    rep_datasets = ["alboran", "castor", "event_0322_a"]
    rep_labels = ["Alboran", "Castor", "event\_0322\_a"]
    rep_colors = [C_AD, "#1b7837", "#762a83"]
    rep_markers = ["o", "s", "^"]
    
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.2))
    
    # (a) Block size: CR vs block_channels
    ax = axes[0]
    for i, ds in enumerate(rep_datasets):
        sub = df_blk[df_blk["dataset"] == ds].sort_values("block_channels")
        if len(sub) > 0:
            ax.plot(sub["block_channels"], sub["cr"], f"{rep_markers[i]}-",
                    color=rep_colors[i], label=rep_labels[i],
                    markersize=6, markeredgecolor="white", markeredgewidth=0.5, linewidth=2)
            # DASPack baseline (dashed)
            ax.axhline(y=sub["dp_cr"].iloc[0], color=rep_colors[i],
                       linestyle="--", alpha=0.35, linewidth=1.2)
    ax.set_xlabel("Block size (channels)", fontsize=11)
    ax.set_ylabel("Compression Ratio", fontsize=11)
    ax.set_title("(a) Block size sensitivity", fontsize=11, fontweight="bold")
    ax.legend(fontsize=9, loc="lower right", framealpha=0.9)
    
    # (b) Fraction: normalized MSE ratio (mean ± range across 7 datasets)
    ax = axes[1]
    all_fracs = sorted(df_frac["fraction"].unique())
    ratios_all = []
    for frac in all_fracs:
        sub = df_frac[df_frac["fraction"] == frac]
        ratios = sub["mse"] / sub["dp_mse"] * 100
        ratios_all.append(ratios.values)
    ratios_all = np.array(ratios_all)
    
    mean_ratio = ratios_all.mean(axis=1)
    std_ratio = ratios_all.std(axis=1)
    min_ratio = ratios_all.min(axis=1)
    max_ratio = ratios_all.max(axis=1)
    
    frac_pct = [f * 100 for f in all_fracs]
    
    # Shaded range
    ax.fill_between(frac_pct, min_ratio, max_ratio, color=C_AD, alpha=0.12, label="Range (7 datasets)")
    # Mean line
    ax.plot(frac_pct, mean_ratio, "o-", color=C_AD, markersize=6,
            markeredgecolor="white", markeredgewidth=0.5, linewidth=2, label="Mean")
    # DASPack baseline
    ax.axhline(y=100, color=C_DP, linestyle="--", linewidth=1.5, label="DASPack baseline")
    
    ax.set_xlabel("High-energy fraction (%)", fontsize=11)
    ax.set_ylabel("Overall MSE / DASPack MSE (%)", fontsize=11)
    ax.set_title("(b) Fraction sensitivity", fontsize=11, fontweight="bold")
    ax.legend(fontsize=9, loc="upper right", framealpha=0.9)
    ax.set_ylim(50, 105)
    
    plt.tight_layout(pad=0.5, w_pad=1.0)
    fig.savefig(os.path.join(OUT, "fig4_sensitivity.png"), bbox_inches="tight",
                facecolor="white", edgecolor="none")
    plt.close()
    print("Figure 4 done (sensitivity, 2-panel clean)")

